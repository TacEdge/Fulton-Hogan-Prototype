/** Compact signal constructor. Keeps the project records readable. */
let signalSeq = 0;
function sig(
  dimension: Dimension,
  label: string,
  value: string,
  state: SignalState,
  sourceSystemId: string,
  ageHours: number,
  note?: string,
): Signal {
  signalSeq += 1;
  return {
    id: `sig-${signalSeq}-${dimension}`,
    dimension,
    label,
    value,
    state,
    sourceSystemId,
    ageHours,
    note,
  };
}

/** Signals every project carries. Overrides replace by dimension. */
function baseSignals(opts: {
  variance: number;
  ageHours: number;
  progressSource?: string;
}): Signal[] {
  const { variance, ageHours } = opts;
  const varianceState: SignalState = variance <= -10 ? "act" : variance <= -4 ? "watch" : "ok";
  return [
    sig(
      "delivery-progress",
      "Delivery progress",
      variance === 0 ? "On programme" : `${Math.abs(variance)}% ${variance < 0 ? "behind" : "ahead"} of planned`,
      varianceState,
      opts.progressSource ?? "project-controls",
      ageHours,
    ),
    sig("programme-confidence", "Programme confidence", "Baseline holding", "ok", "scheduling", ageHours),
    sig("quality", "Quality", "No open non-conformance", "ok", "quality-system", ageHours),
    sig("safety", "Safety", "No open corrective action", "ok", "safety-system", ageHours),
    sig("commercial", "Commercial", "Within forecast", "ok", "financial-system", ageHours + 6),
    sig("approvals", "Approvals", "No approval overdue", "ok", "document-control", ageHours),
    sig("constraints", "Constraints", "No active constraint", "ok", "m-field", ageHours),
    sig(
      "data-freshness",
      "Data freshness",
      ageHours >= 72 ? "No refresh in over three days" : "All sources reporting",
      ageHours >= 72 ? "act" : ageHours >= 24 ? "watch" : "ok",
      "arcgis",
      ageHours,
    ),
  ];
}

/** Replace base signals by dimension. */
function withSignals(base: Signal[], overrides: Signal[]): Signal[] {
  const map = new Map(base.map((s) => [s.dimension, s]));
  for (const o of overrides) map.set(o.dimension, o);
  return [...map.values()];
}

